import { useEffect, useRef, useState } from 'react';
import { createTaskSheetPull, TASK_SHEET_PULL_SETTLE_MS } from './taskSheetPull';

const controls = 'input,textarea,select,button,a,[contenteditable]:not([contenteditable="false"]),[role="slider"],iframe,video,audio';
const selectedText = () => !!window.getSelection()?.toString();
function atScrollTop(target: HTMLElement, sheet: HTMLElement) {
  // Header/handle touches are outside the scrolling body. They still obey the
  // same boundary, rather than closing a sheet whose content is halfway down.
  if ((sheet.querySelector<HTMLElement>('[data-sheet-scroll]')?.scrollTop ?? 0) > 1) return false;
  for (let element: HTMLElement | null = target; element && element !== sheet; element = element.parentElement) {
    if (element.scrollHeight > element.clientHeight + 1 && /auto|scroll/.test(getComputedStyle(element).overflowY) && element.scrollTop > 1) return false;
  }
  return true;
}

/** Touch events survive the pointercancel generated by native scrolling, so a
 * finger can scroll to the top and continue into the pull in one movement. */
export function useTaskSheetPull(enabled: boolean, taskId: string | null, onDismiss: () => Promise<void>) {
  const [element, ref] = useState<HTMLDivElement | null>(null);
  const dismiss = useRef(onDismiss);
  dismiss.current = onDismiss;
  useEffect(() => {
    if (!enabled || !element) return;
    const scroller = element.querySelector<HTMLElement>('[data-sheet-scroll]');
    const previousOverscroll = scroller?.style.overscrollBehaviorY;
    // Keep native content scrolling, but reserve boundary bounce for this sheet
    // and prevent scroll chaining into the page behind its modal overlay.
    if (scroller) scroller.style.overscrollBehaviorY = 'none';
    let gesture: ReturnType<typeof createTaskSheetPull> | null = null;
    let target: HTMLElement | null = null;
    let touchId: number | null = null;
    let closing = false;
    let disposed = false;
    let settle: ReturnType<typeof setTimeout> | undefined;
    const paint = (offset: number, animate: boolean) => {
      element.style.setProperty('--task-sheet-pull-duration', animate ? `${TASK_SHEET_PULL_SETTLE_MS}ms` : '0ms');
      element.style.setProperty('--task-sheet-pull', `${offset}px`);
    };
    const restore = () => {
      if (disposed) return;
      closing = false;
      element.removeAttribute('data-pull-state');
      element.style.removeProperty('--task-sheet-pull');
      element.style.removeProperty('--task-sheet-pull-duration');
    };
    const rebound = () => {
      clearTimeout(settle);
      paint(0, true);
      element.setAttribute('data-pull-state', 'settling');
      settle = setTimeout(restore, TASK_SHEET_PULL_SETTLE_MS);
    };
    const cancel = () => {
      gesture = null; target = null; touchId = null;
      if (!closing) rebound();
    };
    const start = (event: TouchEvent) => {
      if (closing) return;
      clearTimeout(settle);
      restore();
      if (event.touches.length !== 1 || selectedText()) { cancel(); return; }
      const origin = event.target instanceof HTMLElement ? event.target : event.target instanceof Element ? event.target.parentElement : null;
      if (!origin || origin.closest(controls)) { gesture = null; target = null; touchId = null; return; }
      target = origin;
      const touch = event.touches[0]!;
      touchId = touch.identifier;
      gesture = createTaskSheetPull({ x: touch.clientX, y: touch.clientY }, atScrollTop(target, element));
    };
    const move = (event: TouchEvent) => {
      if (!gesture || !target || closing) return;
      if (event.touches.length !== 1 || selectedText()) { cancel(); return; }
      const touch = Array.from(event.touches).find(item => item.identifier === touchId);
      if (!touch) { cancel(); return; }
      const { pulling, offset } = gesture.move({ x: touch.clientX, y: touch.clientY }, atScrollTop(target, element));
      if (pulling) {
        if (event.cancelable) event.preventDefault();
        element.setAttribute('data-pull-state', 'dragging');
        paint(offset, false);
      } else if (element.getAttribute('data-pull-state') === 'dragging') paint(0, false);
    };
    const end = (event: TouchEvent) => {
      const touch = Array.from(event.changedTouches).find(item => item.identifier === touchId);
      if (!gesture || !target || !touch) return;
      // The last touchmove may precede lift-off, especially on a quick pull or
      // reversal. Decide from the final finger position rather than stale input.
      gesture.move({ x: touch.clientX, y: touch.clientY }, atScrollTop(target, element));
      const close = gesture.shouldDismiss();
      gesture = null; target = null; touchId = null;
      if (!close) { rebound(); return; }
      closing = true;
      const finish = dismiss.current;
      element.setAttribute('data-pull-state', 'closing');
      paint(element.getBoundingClientRect().height + 32, true);
      settle = setTimeout(() => {
        if (!disposed) void finish().then(restore, restore);
      }, TASK_SHEET_PULL_SETTLE_MS);
    };
    element.addEventListener('touchstart', start, { passive: true });
    element.addEventListener('touchmove', move, { passive: false });
    element.addEventListener('touchend', end);
    element.addEventListener('touchcancel', cancel);
    return () => {
      disposed = true;
      clearTimeout(settle);
      element.removeEventListener('touchstart', start);
      element.removeEventListener('touchmove', move);
      element.removeEventListener('touchend', end);
      element.removeEventListener('touchcancel', cancel);
      element.removeAttribute('data-pull-state');
      element.style.removeProperty('--task-sheet-pull');
      element.style.removeProperty('--task-sheet-pull-duration');
      if (scroller) scroller.style.overscrollBehaviorY = previousOverscroll ?? '';
    };
  }, [enabled, element, taskId]);
  return ref;
}
