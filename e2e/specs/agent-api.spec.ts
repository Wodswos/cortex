import { test, expect } from '@playwright/test';
test.use({ serviceWorkers: 'block' });
test('settings creates revocable tokens, Agent writes reach the live page, and Swagger executes authenticated reads', async ({ page, context, baseURL }, testInfo) => {
  const invite = await context.request.post('/api/invites', { headers: { Cookie: process.env.E2E_ADMIN_COOKIE! }, data: {} });
  expect(invite.ok()).toBe(true);
  const { code } = await invite.json();
  expect((await context.request.post('/api/auth/register', { data: { username: `agent_${Date.now()}`, password: 'fixture-password', inviteCode: code } })).ok()).toBe(true);
  await page.goto('/settings');
  await page.getByLabel('Agent Token 名称', { exact: true }).fill('本机 Agent');
  await page.getByLabel('Agent Token 权限', { exact: true }).selectOption('write');
  await page.getByRole('button', { name: '创建 Token', exact: true }).click();
  const secret = page.getByRole('textbox', { name: '新建的 Agent Token', exact: true });
  await expect(secret).toHaveValue(/^ctx_[a-f0-9]{64}$/);
  const token = await secret.inputValue(), headers = { Authorization: `Bearer ${token}` };
  const project = await context.request.post('/api/v1/projects', { headers, data: { title: 'Agent 项目' } }).then(response => response.json());
  await expect(page.getByRole('navigation', { name: '项目', exact: true }).getByRole('link', { name: 'Agent 项目', exact: true })).toBeVisible();
  const task = await context.request.post('/api/v1/tasks', { headers, data: { title: 'Agent 创建的任务', parentId: project.data.id } }).then(response => response.json());
  await page.getByRole('navigation', { name: '项目', exact: true }).getByRole('link', { name: 'Agent 项目', exact: true }).click();
  await expect(page.getByText('Agent 创建的任务', { exact: true })).toBeVisible();
  await context.request.patch(`/api/v1/tasks/${task.data.id}`, { headers, data: { title: 'Agent 实时更新' } });
  await expect(page.getByText('Agent 实时更新', { exact: true })).toBeVisible();
  const docs = await context.newPage();
  await docs.goto('/api/docs');
  await expect(docs.getByRole('heading', { name: /Cortex Agent API/ })).toBeVisible();
  await expect(docs.getByText(/Unable to render this definition|Failed to load API definition/)).toHaveCount(0);
  await docs.getByRole('button', { name: /^Authorize/ }).click();
  await docs.locator('.auth-container input').fill(token);
  await docs.locator('.dialog-ux').getByRole('button', { name: 'Apply credentials', exact: true }).click();
  await docs.locator('.dialog-ux').getByRole('button', { name: 'Close', exact: true }).click();
  const operation = docs.locator('#operations-项目-get__api_v1_projects');
  await operation.locator('.opblock-summary').click();
  await operation.getByRole('button', { name: 'Try it out', exact: true }).click();
  await operation.getByRole('button', { name: 'Execute', exact: true }).click();
  await expect(operation.locator('.live-responses-table tbody .response-col_status')).toContainText('200');
  await expect(operation.locator('.live-responses-table .highlight-code').first()).toContainText('Agent 项目');
  await docs.screenshot({ path: testInfo.outputPath('swagger-agent-api.png') });
  await docs.close();
  await page.goto('/settings'); await expect(secret).toHaveCount(0);
  await page.getByRole('button', { name: '撤销 Token 本机 Agent', exact: true }).click();
  await expect(page.getByRole('button', { name: '撤销 Token 本机 Agent', exact: true })).toHaveCount(0);
  expect((await context.request.get(`${baseURL}/api/v1/projects`, { headers })).status()).toBe(401);
});
